// `em-contract augment`: derive an augment-decorator file for a model's generated TypeSpec
// contract (em#446 note: "generating those augments from the export JSON is companion-tool
// scope"). Two input documents normalize into one AugmentSource:
//
//  - `em export` JSON (full fidelity: identity + composite + external DCB tags)
//  - `em api surface --json` (em#448, the companion-tool interface; schema 1.0 carries
//    field-level identity flags only — see src/surfaceDoc.ts)
//
// The mapping:
//  - identity DCB tags on public events -> `@@header(...)` candidates; the event's first
//    identity tag additionally -> `@@correlationId(...)` (the typespec-asyncapi idiom is
//    `@header @correlationId` on the same correlation field)
//  - composite/external DCB tags -> comment notes (computed keys; not expressible as an
//    augment against a declared field)
//  - `assigned` fields on public events -> comment notes
//
// Candidates are emitted commented-out by default — a binding author reviews and activates —
// or active with `{ active: true }`. Deterministic: output is a pure function of the input
// document + options; no timestamps, no versions, no absolute paths.

import { dedupe, fieldIdentifier, pascalCase, TagExport } from "./exportDoc.js";

export const AUGMENT_HEADER_LINE = "// GENERATED by em-contract augment — review candidates, then own this file.";

export interface AugmentEvent {
  name: string;
  /** DCB tags in declaration order (identity tags synthesized from field flags for surface input). */
  tags: TagExport[];
  /** `assigned` field names in declaration order. */
  assignedFields: string[];
}

/** The normalized input both document readers produce. */
export interface AugmentSource {
  /** Basename of the model/source file, for the header (never an absolute path). */
  sourceName: string;
  /** e.g. `em export schema 1.20` or `em api surface schema 1.0`. */
  schemaLabel: string;
  /** The contract's namespace (pascalCase of the model name/key). */
  namespace: string;
  /** Reachable declared type names in document order — they claim emitted names first. */
  typeNames: string[];
  /** Public events in timeline order. */
  events: AugmentEvent[];
  /** Input-level caveats, surfaced as warnings (stderr material). */
  warnings: string[];
}

export interface AugmentOptions {
  /** Emit decorator lines active instead of commented-out candidates. */
  active?: boolean;
  /** Relative path to the generated contract, for an `import` line (omitted when absent). */
  contractImport?: string | null;
}

export interface AugmentResult {
  /** TypeSpec source text, trailing newline included. */
  text: string;
  /** Human-facing notes (stderr material): tagged-but-internal events, schema caveats, etc. */
  warnings: string[];
}

export function buildAugment(src: AugmentSource, options: AugmentOptions = {}): AugmentResult {
  const active = options.active === true;
  const ns = src.namespace;

  // Mirror `buildApiContract`'s naming: reachable declared types claim names first (document
  // order), then public events — views and command payloads dedupe after events, so they can
  // never affect an event's emitted name.
  const usedNames = new Set<string>();
  for (const t of src.typeNames) dedupe(pascalCase(t), usedNames, "_");

  const decorator = (line: string) => (active ? line : `// ${line}`);
  const sections: string[] = [];

  for (const event of src.events) {
    const modelName = dedupe(pascalCase(event.name), usedNames, "_");
    const target = (field: string) => `${ns}.${modelName}.${fieldIdentifier(field)}`;
    const lines: string[] = [];

    let correlationDone = false;
    for (const t of event.tags.filter((t) => t.kind === "identity")) {
      const field = t.fields?.[0];
      if (!field) continue;
      if (!correlationDone) {
        lines.push(decorator(`@@correlationId(${target(field)});`) + ` // DCB identity tag \`${t.key}\``);
        correlationDone = true;
      }
      lines.push(decorator(`@@header(${target(field)});`) + ` // DCB identity tag \`${t.key}\``);
    }
    for (const t of event.tags.filter((t) => t.kind === "composite")) {
      lines.push(
        `// DCB composite tag \`${t.key}\` from ${(t.fields ?? []).join(", ")} — computed key; derive it at publish time (no augment target).`,
      );
    }
    for (const t of event.tags.filter((t) => t.kind === "external")) {
      lines.push(`// DCB external tag \`${t.key}\`: ${t.description ?? "(no description)"} — computed externally; no augment target.`);
    }
    for (const f of event.assignedFields) {
      lines.push(`// ${target(f)} is system-assigned — not supplied by the triggering command.`);
    }

    if (lines.length > 0) {
      sections.push([`// event "${event.name}" -> model ${ns}.${modelName}`, ...lines].join("\n"));
    }
  }

  const header = [
    AUGMENT_HEADER_LINE,
    `// Source: ${src.sourceName} (${src.schemaLabel})`,
    `// Contract: namespace ${ns} (em api generate)`,
    "// Candidates come from the model's DCB tags and `assigned` fields on public events.",
  ];

  const prelude: string[] = [];
  const imp = (line: string) => (active ? line : `// ${line}`);
  if (sections.some((s) => s.includes("@@correlationId") || s.includes("@@header"))) {
    prelude.push(
      "//",
      "// `@@correlationId`/`@@header` come from the typespec-asyncapi decorator library; the",
      "// generated contract must be in the same compilation for the targets to resolve.",
      imp(`import "typespec-asyncapi";`),
    );
    if (options.contractImport) prelude.push(imp(`import ${JSON.stringify(options.contractImport)};`));
    prelude.push(imp("using AsyncAPI;"));
  } else if (options.contractImport) {
    prelude.push("//", imp(`import ${JSON.stringify(options.contractImport)};`));
  }

  if (sections.length === 0) {
    sections.push("// No public event carries a DCB tag or an `assigned` field — nothing to augment.");
  }

  const text = [...header, ...prelude, "", sections.join("\n\n")].join("\n") + "\n";
  return { text, warnings: [...src.warnings] };
}
