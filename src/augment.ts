// `em-contract augment` v0: from an `em export` document, derive an augment-decorator file
// for the model's generated TypeSpec contract (em#446 note: "generating those augments from
// the export JSON is companion-tool scope").
//
//  - identity DCB tags on public events -> `@@header(...)` candidates; the event's first
//    identity tag additionally -> `@@correlationId(...)` (the typespec-asyncapi idiom is
//    `@header @correlationId` on the same correlation field)
//  - composite/external DCB tags -> comment notes (computed keys; not expressible as an
//    augment against a declared field)
//  - `assigned` fields on public events -> comment notes
//
// Candidates are emitted commented-out by default — a binding author reviews and activates —
// or active with `{ active: true }`. Deterministic: output is a pure function of the export
// document + options; no timestamps, no versions, no absolute paths.

import {
  contractNames,
  ExportDoc,
  fieldIdentifier,
  publicSurfaceOf,
  type ElementExport,
} from "./exportDoc.js";

export const AUGMENT_HEADER_LINE = "// GENERATED by em-contract augment — review candidates, then own this file.";

export interface AugmentOptions {
  /** Emit decorator lines active instead of commented-out candidates. */
  active?: boolean;
  /** Relative path to the generated contract, for an `import` line (omitted when absent). */
  contractImport?: string | null;
}

export interface AugmentResult {
  /** TypeSpec source text, trailing newline included. */
  text: string;
  /** Human-facing notes (stderr material): tagged-but-internal events, etc. */
  warnings: string[];
}

interface EventPlan {
  el: ElementExport;
  modelName: string;
  lines: string[];
}

export function buildAugment(doc: ExportDoc, options: AugmentOptions = {}): AugmentResult {
  const active = options.active === true;
  const names = contractNames(doc);
  const surface = publicSurfaceOf(doc.model.slices);
  const warnings: string[] = [];

  const decorator = (line: string) => (active ? line : `// ${line}`);
  const plans: EventPlan[] = [];

  for (const el of surface.events) {
    const modelName = names.eventModel.get(el.ref)!;
    const target = (field: string) => `${names.namespace}.${modelName}.${fieldIdentifier(field)}`;
    const lines: string[] = [];

    const identityTags = (el.tags ?? []).filter((t) => t.kind === "identity");
    let correlationDone = false;
    for (const t of identityTags) {
      const field = t.fields?.[0];
      if (!field) continue;
      if (!correlationDone) {
        lines.push(decorator(`@@correlationId(${target(field)});`) + ` // DCB identity tag \`${t.key}\``);
        correlationDone = true;
      }
      lines.push(decorator(`@@header(${target(field)});`) + ` // DCB identity tag \`${t.key}\``);
    }
    for (const t of (el.tags ?? []).filter((t) => t.kind === "composite")) {
      lines.push(
        `// DCB composite tag \`${t.key}\` from ${(t.fields ?? []).join(", ")} — computed key; derive it at publish time (no augment target).`,
      );
    }
    for (const t of (el.tags ?? []).filter((t) => t.kind === "external")) {
      lines.push(`// DCB external tag \`${t.key}\`: ${t.description ?? "(no description)"} — computed externally; no augment target.`);
    }
    for (const f of el.fields ?? []) {
      if (f.assigned) {
        lines.push(`// ${target(f.name)} is system-assigned — not supplied by the triggering command.`);
      }
    }

    if (lines.length > 0) plans.push({ el, modelName, lines });
  }

  // Events the contract does not carry cannot be augmented — surface that instead of
  // silently dropping modeled DCB metadata.
  for (const slice of doc.model.slices) {
    for (const el of slice.elements) {
      if (el.kind === "event" && !el.public && (el.tags ?? []).length > 0) {
        warnings.push(
          `event "${el.name}" carries DCB tags but is not public — it is not in the contract, no augment emitted (mark it \`public\` in the model to bind it)`,
        );
      }
    }
  }

  // Basename only: the export's source.path can be absolute, and output must carry no
  // machine-specific paths.
  const sourceName = doc.source.path.split("/").pop() ?? doc.source.path;
  const header = [
    AUGMENT_HEADER_LINE,
    `// Source: ${sourceName} (em export schema ${doc.schemaVersion})`,
    `// Contract: namespace ${names.namespace} (em api generate)`,
    "// Candidates come from the model's DCB tags and `assigned` fields on public events.",
  ];

  const prelude: string[] = [];
  const imp = (line: string) => (active ? line : `// ${line}`);
  if (plans.some((p) => p.lines.some((l) => l.includes("@@correlationId") || l.includes("@@header")))) {
    prelude.push(
      "//",
      "// `@@correlationId`/`@@header` come from the typespec-asyncapi decorator library; the",
      "// generated contract must be in the same compilation for the targets to resolve.",
      imp(`import "typespec-asyncapi";`),
    );
    if (options.contractImport) prelude.push(imp(`import ${JSON.stringify(options.contractImport)};`));
    prelude.push(imp("using AsyncAPI;"));
  } else if (options.contractImport) {
    prelude.push("//", imp(`import ${JSON.stringify(options.contractImport)};`));
  }

  const sections: string[] = [];
  for (const p of plans) {
    sections.push([`// event "${p.el.name}" -> model ${names.namespace}.${p.modelName}`, ...p.lines].join("\n"));
  }
  if (sections.length === 0) {
    sections.push("// No public event carries a DCB tag or an `assigned` field — nothing to augment.");
  }

  const text = [...header, ...prelude, "", sections.join("\n\n")].join("\n") + "\n";
  return { text, warnings };
}
