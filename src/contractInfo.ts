// Compile a generated em contract and distill the facts bind init/check need: the namespace,
// and the Commands/Events/Views surface with payload-model names and fields. This is the
// shared "read the contract semantically" layer — both commands compile with the same pinned
// @typespec/compiler the spike (docs/spike-compiler-api.md) validated.

import { compile, NodeHost, type Interface, type Model, type Namespace, type Program } from "@typespec/compiler";

/** The header line `em api generate` writes; used to sanity-check the input file. */
export const EM_CONTRACT_HEADER = "// GENERATED by em api generate";

export interface OpInfo {
  /** Operation name as declared (`onOrderPlaced`, `submitOrder`, `getOpenOrders`). */
  op: string;
  /** The payload/return model's bare name within the contract namespace. */
  model: string;
  /** The model's property names, in declaration order. */
  fields: string[];
}

export interface ContractInfo {
  namespace: string;
  commands: OpInfo[];
  events: OpInfo[];
  views: OpInfo[];
  /** Every model declared in the contract namespace, with its property names. */
  models: Map<string, string[]>;
}

function modelOf(type: unknown): Model | null {
  const t = type as { kind?: string } | undefined;
  return t && t.kind === "Model" ? (t as Model) : null;
}

function opsOf(iface: Interface | undefined, pick: (op: { parameters: Model; returnType: unknown }) => Model | null): OpInfo[] {
  if (!iface) return [];
  const out: OpInfo[] = [];
  for (const op of iface.operations.values()) {
    const model = pick(op);
    if (!model) continue;
    out.push({ op: op.name, model: model.name, fields: [...model.properties.keys()] });
  }
  return out;
}

export function distillContract(ns: Namespace): ContractInfo {
  const models = new Map<string, string[]>();
  for (const m of ns.models.values()) models.set(m.name, [...m.properties.keys()]);
  const payload = (op: { parameters: Model }) => modelOf(op.parameters.properties.get("payload")?.type);
  const returned = (op: { returnType: unknown }) => modelOf(op.returnType);
  return {
    namespace: ns.name,
    commands: opsOf(ns.interfaces.get("Commands"), (op) => payload(op)),
    events: opsOf(ns.interfaces.get("Events"), (op) => payload(op)),
    views: opsOf(ns.interfaces.get("Views"), (op) => returned(op)),
    models,
  };
}

export interface CompiledContract {
  program: Program;
  info: ContractInfo;
}

/**
 * Compile a contract file standalone and distill it. Throws with a user-facing message when
 * the file has errors or holds no single namespace (em contracts always emit exactly one).
 */
export async function loadContract(path: string): Promise<CompiledContract> {
  const program = await compile(NodeHost, path);
  const errors = program.diagnostics.filter((d) => d.severity === "error");
  if (errors.length > 0) {
    throw new Error(`${path}: contract does not compile — ${errors[0].message}`);
  }
  const namespaces = [...program.getGlobalNamespaceType().namespaces.values()].filter(
    (n) => n.name !== "TypeSpec" && n.namespaces.size + n.models.size + n.interfaces.size > 0,
  );
  if (namespaces.length !== 1) {
    throw new Error(
      `${path}: expected exactly one declared namespace (an em api generate contract), found ${namespaces.length}`,
    );
  }
  return { program, info: distillContract(namespaces[0]) };
}
